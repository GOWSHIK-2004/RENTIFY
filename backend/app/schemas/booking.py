from datetime import date, datetime
from decimal import Decimal
from typing import Annotated, Literal

from pydantic import BaseModel, Field, StringConstraints

from app.models.booking import BookingStatus
from app.models.inventory import EquipmentCondition
from app.models.payment import PaymentStatus


class QuoteRequest(BaseModel):
    product_id: int
    pickup_date: date
    return_date: date


class QuoteResponse(BaseModel):
    product_id: int
    pickup_date: date
    return_date: date
    rental_days: int
    daily_price: Decimal
    total_amount: Decimal
    available: bool
    available_units: int


class BookingCreate(BaseModel):
    product_id: int
    pickup_date: date
    return_date: date
    # The total the customer saw. Never used as the price: it only lets the
    # server detect that the price changed since the quote.
    expected_total: Decimal
    # Generated by the checkout page once per attempt; makes retries safe.
    idempotency_key: Annotated[str, StringConstraints(strip_whitespace=True, min_length=8, max_length=100)]
    # Simulated checkout: the user picks the outcome. No real payment exists.
    payment_outcome: Literal["success", "failure"] = "success"


class CancelRequest(BaseModel):
    reason: Annotated[str, StringConstraints(strip_whitespace=True, max_length=500)] | None = None


class ReturnRequest(BaseModel):
    """Optionally record the equipment's condition when it comes back."""

    condition: EquipmentCondition | None = None


class BookingProduct(BaseModel):
    id: int
    name: str
    brand: str
    model: str
    image_url: str | None


class BookingCustomer(BaseModel):
    id: int
    full_name: str
    email: str


class BookingResponse(BaseModel):
    id: int
    booking_reference: str
    status: BookingStatus
    product: BookingProduct
    customer: BookingCustomer
    asset_code: str
    pickup_date: date
    return_date: date
    rental_days: int
    daily_price: Decimal
    total_amount: Decimal
    payment_status: PaymentStatus | None
    transaction_reference: str | None
    actual_pickup_at: datetime | None
    actual_return_at: datetime | None
    cancellation_reason: str | None
    created_at: datetime
    # Computed on the fly, never stored.
    is_overdue: bool
    affected_by_overdue: bool
    can_cancel: bool
    review_id: int | None


class BookingListResponse(BaseModel):
    items: list[BookingResponse]
    total: int
    page: int
    page_size: int
    pages: int = Field(ge=0)
